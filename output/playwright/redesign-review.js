async (page) => {
  const base = 'http://127.0.0.1:3000';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const noOverflow = async () => {
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Horizontal overflow on ' + page.url());
  };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/');
  if (!await page.title().then(title => title.includes('Natayark SkinServer'))) throw new Error('Wrong product name');
  await page.locator('.home-textures .texture-card').first().waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.home-textures img')].every(image => image.complete && image.naturalWidth > 0));
  await noOverflow();
  await page.screenshot({ path: 'output/playwright/redesign-home.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow();
  await page.screenshot({ path: 'output/playwright/redesign-home-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/user');
  await page.screenshot({ path: 'output/playwright/redesign-dashboard.png', fullPage: true });
  await page.locator('[data-theme-toggle]').click();
  await page.waitForFunction(() => document.getAnimations().every(animation => animation.playState !== 'running'));
  await page.screenshot({ path: 'output/playwright/redesign-dashboard-dark.png', fullPage: true });
  await page.locator('[data-theme-toggle]').click();
  await page.waitForFunction(() => document.getAnimations().every(animation => animation.playState !== 'running'));
  await page.goto(base + '/skinlib');
  const card = page.locator('a.texture-card').first();
  await card.hover();
  const style = await card.evaluate(element => ({ transform: getComputedStyle(element).transform, shadow: getComputedStyle(element).boxShadow }));
  if (style.transform !== 'none' || style.shadow !== 'none') throw new Error('Card hover moves or casts a shadow');
  await page.screenshot({ path: 'output/playwright/redesign-skinlib.png', fullPage: true });
  await page.goto(base + '/user/player');
  await page.locator('[data-dialog-open="dialog-add"]').first().click();
  const dialog = page.locator('#dialog-add');
  await dialog.waitFor({ state: 'visible' });
  await page.screenshot({ path: 'output/playwright/redesign-dialog.png', fullPage: true });
  await dialog.locator('[data-dialog-close]').first().click();
  await dialog.waitFor({ state: 'hidden' });
  await page.locator('[data-action="rename-player"]').first().click();
  const prompt = page.locator('dialog[open]');
  await prompt.waitFor({ state: 'visible' });
  await prompt.locator('[data-cancel]').click();
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().right <= 0);
  await noOverflow();
  await page.screenshot({ path: 'output/playwright/redesign-players-mobile.png', fullPage: true });
  await page.locator('[data-sidebar-toggle]').click();
  await page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().left === 0);
  await page.screenshot({ path: 'output/playwright/redesign-menu-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().right <= 0);
  await page.locator('[data-sidebar-toggle]').click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  if (await page.evaluate(() => document.body.style.overflow === 'hidden')) throw new Error('Desktop scroll remains locked');
  await page.getByRole('button', { name: 'Review6e9ed02a', exact: true }).click();
  await page.locator('.dropdown-menu:visible').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.dropdown-menu:visible').waitFor({ state: 'hidden' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('[data-dialog-open="dialog-add"]').first().click();
  const duration = await dialog.evaluate(element => getComputedStyle(element).animationDuration);
  if (parseFloat(duration) > 0.001) throw new Error('Reduced motion not honored');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  if (errors.length) throw new Error(errors.join('\n'));
  return { hover: style, reducedMotion: duration, javascriptErrors: errors.length };
}
