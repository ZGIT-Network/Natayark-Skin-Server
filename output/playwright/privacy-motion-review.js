async page=>{
  const base='http://127.0.0.1:3000';
  const ensure=(value,message)=>{if(!value)throw new Error(message);};
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'no-preference',colorScheme:'dark'});
  await page.goto(base+'/user');
  ensure(await page.locator('[data-private-identifier]').count()===0,'Dashboard still contains UUID controls');
  await page.locator('a[href="/user/player"]').first().click();
  await page.waitForURL('**/user/player');
  await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running'));
  ensure(await page.locator('[data-page-content]').evaluate(element=>getComputedStyle(element).transform)==='none','Page keeps a transform after animation');
  for(const route of ['/user/player','/user/verification']) {
    await page.goto(base+route);
    const control=page.locator('[data-private-identifier]').first();
    const value=control.locator('[data-private-value]');
    const masked=await value.textContent();
    ensure(masked.includes('…')&&masked.length<16,'UUID is not masked');
    const response=await page.request.get(base+await control.getAttribute('data-uuid-url'));
    const uuid=(await response.json()).uuid;
    ensure(!(await page.content()).includes(uuid),'Full UUID leaked in initial HTML');
    await control.getByRole('button',{name:'显示完整 UUID',exact:true}).click();
    await page.waitForFunction(expected=>document.querySelector('[data-private-value]').textContent===expected,uuid);
    await control.getByRole('button',{name:'隐藏完整 UUID',exact:true}).click();
    ensure(await value.textContent()===masked,'Hide UUID failed');
    await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.__reviewCopied=text;}}}));
    await control.getByRole('button',{name:'复制完整 UUID',exact:true}).click();
    await page.waitForFunction(expected=>window.__reviewCopied===expected,uuid);
    ensure(await value.textContent()===masked,'Copy reveals UUID');
    await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running'));
    await page.screenshot({path:'output/playwright/'+(route.endsWith('verification')?'verification-private':'player-uuid-private')+'.png',fullPage:true});
    await control.getByRole('button',{name:'显示完整 UUID',exact:true}).click();
    await page.waitForFunction(expected=>document.querySelector('[data-private-value]').textContent===expected,uuid);
    await page.goto(base+'/user');
    await page.goBack();
    ensure(await page.locator('[data-private-value]').first().textContent()===masked,'Back navigation reveals a UUID');
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base+'/user');
  ensure(await page.locator('[data-page-content]').evaluate(e=>getComputedStyle(e).animationName)==='none','Reduced-motion entry animation');
  await page.locator('a[href="/user/player"]').first().click();
  await page.waitForURL('**/user/player');
  ensure(await page.locator('[data-page-content]').evaluate(e=>getComputedStyle(e).animationName)==='none','Reduced motion still animates navigation');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(base+'/admin/textures');
  await page.waitForFunction(()=>[...document.querySelectorAll('.library-card:nth-child(-n+4) img')].every(image=>image.complete&&image.naturalWidth));
  await page.screenshot({path:'output/playwright/admin-texture-cards-dark.png',fullPage:false});
  await page.getByRole('link',{name:'下一页',exact:true}).click();
  await page.waitForURL('**page=2*');
  await page.getByRole('link',{name:'清除筛选',exact:true}).click();
  await page.waitForURL('**/admin/textures');
  await page.getByRole('combobox',{name:'材质类型',exact:true}).selectOption('cape');
  await page.locator('.library-search').getByRole('button',{name:'搜索',exact:true}).click();
  await page.waitForURL('**type=cape*');
  ensure((await page.locator('.library-model').allTextContents()).every(value=>value==='披风'),'Type filter failed');
  await page.goto(base+'/admin/settings#appearance');
  await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running'));
  await page.screenshot({path:'output/playwright/appearance-settings.png',fullPage:true});
  await page.emulateMedia({colorScheme:'light'});
  ensure(errors.length===0,errors.join('\n'));
  return{uuidMasked:true,onDemandReveal:true,copyWithoutReveal:true,historyPrivate:true,ordinaryPageFade:true,reducedMotion:true,pagination:true,typeFilter:true,errors};
}
