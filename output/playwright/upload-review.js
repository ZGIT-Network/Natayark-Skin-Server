async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.unroute('**/api/skinlib');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:3002/skinlib/upload');
  const initialScore = Number(await page.locator('#upload-form').getAttribute('data-score'));
  if (await page.locator('#file-preview-panel').isVisible()) throw new Error('Empty preview must be hidden');
  await page.locator('#file').setInputFiles('D:/Projects/MCNSKIN/.test-artifacts/review-skin.png');
  await page.locator('#file-preview').waitFor({ state: 'visible' });
  await page.waitForFunction(() => document.querySelector('#file-preview').naturalWidth === 64);
  const publicEstimate = await page.locator('#upload-estimate').innerText();
  await page.getByRole('radio', { name: /^私有/ }).check();
  const privateEstimate = await page.locator('#upload-estimate').innerText();
  if (privateEstimate === publicEstimate) throw new Error('Visibility must update the estimated fee');
  await page.getByRole('radio', { name: /^公开/ }).check();
  const estimate = await page.locator('#upload-estimate').innerText();
  if (!estimate.includes('预计消耗') && !estimate.includes('预计获得')) throw new Error('No fee estimate');
  await page.getByRole('combobox', { name: '类型', exact: true }).selectOption('cape');
  if (!await page.locator('#model').isDisabled()) throw new Error('Cape model must be disabled');
  await page.getByRole('combobox', { name: '类型', exact: true }).selectOption('skin');
  if (await page.locator('#model').isDisabled()) throw new Error('Skin model must be enabled');
  await page.screenshot({ path: 'output/playwright/upload-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('[data-sidebar]').getBoundingClientRect().right <= 0);
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Upload mobile overflow');
  await page.screenshot({ path: 'output/playwright/upload-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '上传', exact: true }).click();
  await page.waitForURL('**/skinlib/show/*');
  const tid = Number(page.url().split('/').at(-1));
  const expected = /预计消耗 (\d+)/.exec(estimate) || /预计获得 (\d+)/.exec(estimate);
  const cost = Number(expected[1]) * (estimate.includes('预计获得') ? -1 : 1);
  const uploadPage = await page.request.get('http://127.0.0.1:3002/skinlib/upload');
  const settledScore = Number(/data-score="(\d+)"/.exec(await uploadPage.text())[1]);
  if (initialScore - settledScore !== cost) throw new Error('Estimate differs from server settlement');
  const apply = page.getByRole('main').getByRole('button', { name: 'Review30a6a592', exact: true });
  await apply.click();
  await page.getByRole('button', { name: 'Review30a6a592 · 已应用', exact: true }).waitFor();
  await page.reload();
  if (!await page.getByRole('button', { name: 'Review30a6a592 · 已应用', exact: true }).isDisabled()) throw new Error('Applied state lost after reload');
  await page.screenshot({ path: 'output/playwright/applied-desktop.png', fullPage: true });
  console.log(JSON.stringify({ tid, cost, initialScore, settledScore, estimate, errors }));
  if (errors.length) throw new Error(errors.join('\n'));
}
