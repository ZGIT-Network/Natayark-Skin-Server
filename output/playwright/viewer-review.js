async (page) => {
  const base = 'http://127.0.0.1:3000';
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  const ensure=(value,message)=>{if(!value)throw new Error(message);};
  const ready=async container=>{await container.locator('[data-viewer-status]').waitFor({state:'hidden'}); ensure(await container.getAttribute('data-ready')==='true','Viewer did not load');};
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(base+'/skinlib/upload');
  let container=page.locator('[data-skin-viewer]');
  await ready(container);
  await page.locator('#file').setInputFiles('D:/Projects/MCNSKIN/.test-artifacts/review-skin.png');
  await page.locator('#model').selectOption('slim');
  await ready(container);
  ensure(await container.evaluate(element=>element.__viewer.playerObject.skin.modelType)==='slim','Slim model failed');
  await container.getByRole('button',{name:'切换行走与奔跑',exact:true}).click();
  ensure(await container.getAttribute('data-animation')==='run','Run animation failed');
  await container.getByRole('button',{name:'暂停动画',exact:true}).click();
  ensure(await container.evaluate(element=>element.__viewer.animation.paused),'Pause failed');
  await container.getByRole('button',{name:'播放动画',exact:true}).click();
  await container.getByRole('button',{name:'自动旋转',exact:true}).click();
  ensure(!await container.evaluate(element=>element.__viewer.autoRotate),'Rotation toggle failed');
  await container.getByRole('button',{name:'重置预览',exact:true}).click();
  ensure(await container.evaluate(element=>element.__viewer.animation===null),'Reset failed');
  await container.getByRole('button',{name:'黑色背景',exact:true}).click();
  ensure(await container.evaluate(element=>element.__viewer.background.getHexString())==='000000','Background color failed');
  await container.getByRole('button',{name:'上一个场景',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-viewer-scene]').textContent==='7 / 7');
  await container.getByRole('button',{name:'下一个场景',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-viewer-scene]').textContent==='1 / 7');
  await container.getByRole('button',{name:'2D',exact:true}).click();
  ensure(await container.evaluate(element=>element.__viewer.renderPaused),'Hidden 3D keeps rendering');
  await container.getByRole('button',{name:'3D',exact:true}).click();
  await container.getByRole('button',{name:'跟随站点背景',exact:true}).click();
  await page.locator('#type').selectOption('cape');
  await page.locator('#file').setInputFiles('D:/Projects/MCNSKIN/.test-artifacts/review-cape.png');
  await ready(container);
  ensure(await container.evaluate(element=>element.__viewer.playerObject.cape.visible),'Cape did not load');
  await page.screenshot({path:'output/playwright/cape-upload-preview.png',fullPage:true});
  await page.locator('#type').selectOption('skin');
  await page.locator('#model').selectOption('slim');
  await page.locator('#file').setInputFiles('D:/Projects/MCNSKIN/.test-artifacts/review-skin.png');
  await page.locator('#name').fill('Viewer regression');
  await page.locator('input[name="public"][value="0"]').check();
  await ready(container);
  await page.locator('#upload-form').getByRole('button',{name:'上传',exact:true}).click();
  await page.waitForURL('**/skinlib/show/*');
  const tid=Number(page.url().split('/').at(-1));
  container=page.locator('[data-skin-viewer]');
  await ready(container);
  await container.getByRole('button',{name:'2D',exact:true}).click();
  await page.waitForFunction(()=>{const image=document.querySelector('[data-viewer-flat-skin]');return image.complete&&image.naturalWidth>0;});
  await page.screenshot({path:'output/playwright/texture-2d-preview.png',fullPage:true});
  await container.getByRole('button',{name:'3D',exact:true}).click();
  const form=page.locator('form[data-action="texture-model"]');
  await form.locator('[name="type"]').selectOption('steve');
  await form.getByRole('button',{name:'修改模型',exact:true}).click();
  await page.waitForEvent('domcontentloaded');
  container=page.locator('[data-skin-viewer]');
  await ready(container);
  ensure(await container.evaluate(element=>element.__viewer.playerObject.skin.modelType)==='default','Saved model not reflected');
  await page.getByRole('button',{name:'重命名',exact:true}).click();
  await page.locator('dialog[open] input').fill('Viewer renamed');
  await page.locator('dialog[open] [data-confirm]').click();
  await page.getByRole('heading',{name:'Viewer renamed',level:1}).waitFor();
  await page.locator('[data-action="apply-texture"]').first().click();
  await page.waitForFunction(()=>document.querySelector('[data-action="apply-texture"]').disabled);
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('[data-sidebar]').getBoundingClientRect().right<=0);
  ensure(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Viewer mobile overflow');
  await page.waitForFunction(()=>{const e=document.querySelector('[data-viewer-viewport]');return e.querySelector('canvas').clientWidth===e.clientWidth;});
  await page.screenshot({path:'output/playwright/texture-preview-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/user/player');
  await page.locator('[data-dialog-open^="dialog-set-"]').first().click();
  container=page.locator('dialog[open] [data-skin-viewer]');
  await ready(container);
  ensure(await container.evaluate(element=>element.__viewer.playerObject.skin.visible),'Player skin preview missing');
  await page.screenshot({path:'output/playwright/player-combined-preview.png',fullPage:true});
  await page.keyboard.press('Escape');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base+'/skinlib/show/'+tid);
  container=page.locator('[data-skin-viewer]');
  await ready(container);
  ensure(await container.getAttribute('data-paused')==='true','Reduced motion not honored');
  ensure(await container.evaluate(element=>!element.__viewer.autoRotate),'Reduced motion auto-rotates');
  await page.emulateMedia({reducedMotion:'no-preference'});
  ensure(errors.length===0,errors.join('\n'));
  return {tid,animations:true,rotation:true,reset:true,backgrounds:7,modelChange:true,rename:true,flatPreview:true,mobile:true,playerPreview:true,reducedMotion:true,errors};
}
