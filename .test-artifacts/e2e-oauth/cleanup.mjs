import { config } from '../../src/config.js';
import mysql from 'mysql2/promise';
import crypto from 'node:crypto';
const conn = await mysql.createConnection({ host: config.db.host, port: config.db.port, user: config.db.user, password: config.db.password, database: config.db.database });
const p = config.db.tablePrefix ?? '';
const [rows] = await conn.execute('SELECT uid FROM \`' + p + 'users\` WHERE email = ?', ['e2e-oauth@example.com']);
if (rows.length) {
  const uid = rows[0].uid;
  await conn.execute('DELETE FROM \`' + p + 'players\` WHERE uid = ?', [uid]);
  await conn.execute('DELETE FROM \`' + p + 'mcn_oauth_identities\` WHERE user_id = ?', [uid]);
  await conn.execute('DELETE FROM \`' + p + 'mcn_web_sessions\` WHERE user_id = ?', [uid]);
  await conn.execute('DELETE FROM \`' + p + 'user_closet\` WHERE user_uid = ?', [uid]);
  await conn.execute('DELETE FROM \`' + p + 'uuid\` WHERE name = ?', ['E2E_OAuth用户']);
  await conn.execute('DELETE FROM \`' + p + 'mcn_registration_rewards\` WHERE uid = ?', [uid]);
  await conn.execute('DELETE FROM \`' + p + 'users\` WHERE uid = ?', [uid]);
  console.log('removed e2e user', uid);
} else console.log('e2e user already gone');
await conn.execute('DELETE FROM \`' + p + 'options\` WHERE option_name = ?', ['oauth_providers']);
await conn.execute('DELETE FROM \`' + p + 'mcn_web_sessions\` WHERE sid_hash = ?', [crypto.createHash('sha256').update('f'.repeat(64)).digest('hex')]);
console.log('cleaned options + session');
await conn.end();
