export function translate(locale: Locale, key: string, values?: Record<string, string | number>): string {
  let message = dictionaries[locale]?.[key] ?? dictionaries.zh_CN[key] ?? key;
  if (values) for (const [name, value] of Object.entries(values)) message = message.split(':' + name).join(String(value));
  return message;
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === 'zh_CN' || value === 'en';
}
